/**
 * Чем за заказ заплатили на самом деле.
 *
 * Покупатель выбирает всего два способа — картой или при получении, — но
 * «при получении» распадается надвое. Если заказ уехал в СДЭК, деньги
 * собирает курьер СДЭК наложенным платежом и он же пробивает чек. Если
 * доставку забрали себе, отправления нет, наложенного платежа тоже — и
 * когда такой заказ отмечают оплаченным, это наличные нашему курьеру.
 *
 * Оплата по ссылке переводит заказ в «картой»: способ меняется в
 * applyPayment, когда деньги дошли. Поэтому «при получении» без
 * отправления — это всегда наличные, а не забытая онлайн-оплата.
 */
export function paymentLabel(order: {
  paymentMethod: string;
  cdek: unknown | null;
}): string {
  if (order.paymentMethod === "online") return "Картой онлайн";
  return order.cdek ? "Наложенным платежом СДЭК" : "Наличными при получении";
}
