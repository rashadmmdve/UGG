/**
 * Два взгляда на цену.
 *
 * В базе `price` — продажная (то, что видит покупатель), `oldPrice` —
 * цена до скидки, если скидка есть. Владелец же вводит «цену» и, при
 * желании, «цену со скидкой»: нет скидочной — действует обычная.
 * Помощники переводят хранимую пару в это представление; обратный
 * перевод делают действия админки.
 *
 * Модуль без server-only: нужен и клиентской таблице цен.
 */
type Priced = { price: number; oldPrice: number | null };

/** Цена без скидки — та, что владелец вводит первой. */
export const basePrice = (p: Priced): number => p.oldPrice ?? p.price;

/** Цена со скидкой; null — скидки нет, действует обычная. */
export const salePrice = (p: Priced): number | null => (p.oldPrice === null ? null : p.price);
