import "server-only";

/**
 * Наименование позиции в чеке.
 *
 * Чек уходит в ФНС и покупателю — и при оплате картой (его формирует
 * ЮKassa), и при оплате при получении (его пробивает СДЭК из позиций
 * накладной). Наименование в обоих случаях берётся отсюда, иначе за один
 * и тот же товар покупатель получал бы чеки с разными названиями.
 *
 * Из названия убираются марка и размер: в чеке нужен сам товар. Пустое
 * после чистки название не годится — 54-ФЗ требует наименование, поэтому
 * в таком случае остаётся исходное.
 */
const BRAND = /^\s*UGG®?\s+/i;

export function receiptItemName(title: string): string {
  const cleaned = title.replace(BRAND, "").trim();
  return cleaned || title.trim();
}
